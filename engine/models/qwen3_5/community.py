"""The 27B family's community packs (ENG-409, from server/setup/community.py): the weight profile of a pack that is
the model (standalone) or an EXL3 overlay over the 27B, through engine/loader.py, and its pack check (none beyond
the registry's). The registry calls these through models/qwen3.8-27b/model.yaml's `community_base.hook`."""

from __future__ import annotations


def env(m: dict, c: dict, d: str) -> str:
    """The weight profile of community entry `c` of model `m`, as ops/serve.env sources it: the pack in its own
    folder `d`, standalone (the pack is the model, QWEN38_MODEL, as --model; #1's loader) or an EXL3 overlay over
    the base (QWEN38_EXL3); the drafters; the vision tower only where the entry says images work; its own
    disk-tier folder. Every value comes from a checked field (the registry's patterns: no quote, space or $)."""
    lines = [f"# Weight profile {c['profile']}: {c['name']} by @{c['author']['github']}, "
             f"{c['format']} {c['bpw']:g} bpw, {c['load']},",
             f"# {c['hf']['repo']}@{c['hf']['revision']}. Generated by server/setup/community.py from",
             f"# models/{m['id']}/community/{c['id']}.json; ops/use-profile.sh {c['profile']} writes it again "
             f"before every switch.",
             f"QSE_WEIGHTS='{c['profile']}'",
             f"QSE_WEIGHTS_HF='{c['hf']['repo']}'",
             f"QSE_WEIGHTS_REVISION='{c['hf']['revision']}'",
             f'QSE_WEIGHTS_DIR="{d}"',
             f"QSE_WEIGHTS_GB='{c['size_gb']:g}'",
             "QSE_WEIGHTS_FILES=",
             "unset QWEN38_EXL3 QWEN38_DRAFT_EXL3 QWEN38_DRAFT_HEAD_EXL3 QSE_ENGINE_FLAGS QSE_ASSETS"]
    if c["load"] == "standalone":
        lines.append('QWEN38_MODEL="${QSE_WEIGHTS_DIR}"')
    else:
        lines.append('QWEN38_EXL3="${QSE_WEIGHTS_DIR}"')
    if c["drafters"] == "tandem-exl3":
        lines += ['QWEN38_DRAFT_EXL3="${HOME}/.qwen38-spark-engine/weights/exl3-drafters-k3"',
                  'QWEN38_DRAFT_HEAD_EXL3="${HOME}/.qwen38-spark-engine/weights/exl3-draft-head-k4"']
    if c["drafters"] in ("tandem-exl3", "dflash2"):
        lines += ['CKPT8="${REPO}/train/ft-b8-v2"', 'CKPT16="${REPO}/train/ft-b16"']
    else:
        # no drafter: start.sh's model flags in place of the 27B's drafter flags
        lines.append('QSE_ENGINE_FLAGS="' + ("--model ${QSE_WEIGHTS_DIR} " if c["load"] == "standalone"
                                             else "") + '--drafter none"')
    lines += _parallel(m)
    if c.get("format") == "exl3":
        # SPD-171: the 27B's EXL3 prefill takes up to 512 rows on the skinny kernel (ops/profiles/_exl3.env)
        lines.append("QWEN38_EXL3_CHUNK_UNTIL=512")
    lines += ["QWEN38_SAMPLE_NUCLEUS=1",
              f"VISION={'on' if c['modalities']['image'] else 'off'}",
              # SPD-167: a text-only pack's limit, which setup.env cannot turn back on (ops/serve.env)
              *([] if c['modalities']['image'] else ["QSE_PACK_VISION=off"]),
              f'QSE_DISK_CACHE="${{HOME}}/.qwen38-spark-engine/cache/disk-community-{c["id"]}"']
    return "\n".join(lines) + "\n"


def _parallel(m: dict) -> list[str]:
    """SPD-165: the base's parallel requests as its Setup Guide defaults them (models/<base>/model.yaml
    `parallelism`: the slots, the side window, the KV pool, the admission floor and the fixed keys), so a
    pack switched in with ops/use-profile.sh serves several chats at once without the guide. A box's
    run/setup.env, read after the profile, still decides. Measured 2026-10-23 on the ThinkingCap pack:
    one request alone at 4 slots + the pool decoded prose at 38.4 tok/s against 37.4 at 1 slot and read
    8K at 867 against 855 tok/s; 2 and 4 at once came to 50.1 and 58.6 tok/s in total against a queue."""
    p = m.get("parallelism") or {}
    k = p.get("knobs") or {}
    if not k:
        return []
    slots = int(p["slots"]["default"])
    cap = p["slots"].get("engine_max")
    if cap:
        slots = min(slots, int(cap))
    out = [f"# SPD-165: parallel requests at the base's Setup Guide defaults (models/{m['id']}/model.yaml)",
           f"{k['slots']}={slots}",
           f"{k['side_window']}={int(p['side_window']['default'])}",
           f"{k['kv_pool']}={'on' if p.get('kv_pool', {}).get('default') else 'off'}",
           f"{k['floor_gb']}={p['floor_gb']['default']:g}"]
    out += [f"{key}={val}" for key, val in (p.get("fixed") or {}).items()]
    return out


